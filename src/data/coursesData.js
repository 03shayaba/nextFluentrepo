// Utility: find any course by slug across all datasets
export function getCourseBySlug(slug) {
  return (
    popularCoursesData.find((c) => c.slug === slug) ||
    trendingCoursesData.find((c) => c.slug === slug) ||
    null
  );
}

// Utility: find any course by numeric id across all datasets
export function getCourseById(id) {
  const numId = Number(id);
  return (
    popularCoursesData.find((c) => c.id === numId) ||
    trendingCoursesData.find((c) => c.id === numId) ||
    null
  );
}
